-- =============================================
-- 动作知识库 exercise_library
-- =============================================
DROP TABLE IF EXISTS exercise_library;

CREATE TABLE exercise_library (
    id           BIGINT AUTO_INCREMENT PRIMARY KEY,
    name         VARCHAR(50)  NOT NULL COMMENT '标准动作名(如"深蹲")',
    aliases      VARCHAR(200) NULL     COMMENT '别名/关键词(逗号分隔)',
    category     VARCHAR(30)  NULL     COMMENT '分类: 热身/力量/有氧/拉伸/核心',
    muscle_group VARCHAR(50)  NULL     COMMENT '主要肌群',
    gif_url      VARCHAR(500) NULL     COMMENT 'GIF动图URL(MinIO)',
    tips         VARCHAR(500) NULL     COMMENT '动作要点(纯文字)',
    difficulty   TINYINT      DEFAULT 1 COMMENT '难度: 1初级/2中级/3高级',
    equipment    VARCHAR(100) NULL     COMMENT '所需器材(空=徒手)',
    created_at   DATETIME     DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_name (name)
) COMMENT='动作知识库' DEFAULT CHARSET=utf8mb4;


